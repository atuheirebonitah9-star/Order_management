class Command(BaseCommand):
    help = "Seed the database with sample customers, restaurants, riders, menu items, orders, payments and reviews."

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear",
            action="store_true",
            help="Delete ALL existing data in the orders app before seeding.",
        )

    @transaction.atomic
    def handle(self, *args, **options):
        if options["clear"]:
            Review.objects.all().delete()
            Payment.objects.all().delete()
            OrderItem.objects.all().delete()
            Order.objects.all().delete()
            MenuItem.objects.all().delete()
            DeliveryRider.objects.all().delete()
            Restaurant.objects.all().delete()
            Customer.objects.all().delete()
            self.stdout.write(self.style.WARNING("Existing data cleared."))
        elif Customer.objects.exists() or Restaurant.objects.exists() or Order.objects.exists():
            self.stdout.write(self.style.WARNING(
                "Database already has data, nothing seeded. Run with --clear to wipe and reseed."
            ))
            return

        customers = {}
        for name, phone, email in CUSTOMERS:
            c = Customer(customer_name=name, phone_contact=phone, email_address=email)
            c.save()
            customers[name] = c

        restaurants = {}
        for name, address, is_open in RESTAURANTS:
            r = Restaurant(name=name, address=address, is_open=is_open)
            r.save()
            restaurants[name] = r

        riders = {}
        for name, status, rating in RIDERS:
            rd = DeliveryRider(name=name, status=status, rating=rating)
            rd.save()
            riders[name] = rd

        menu = {}  # (restaurant name, item name) -> MenuItem
        for rest_name, items in MENU.items():
            for item_name, category, price, available in items:
                m = MenuItem(
                    restaurant=restaurants[rest_name], name=item_name,
                    category=category, price=price, is_available=available,
                )
                m.save()
                menu[(rest_name, item_name)] = m

        n_payments = n_reviews = 0
        for spec in ORDERS:
            order = Order(
                customer=customers[spec["customer"]],
                restaurant=restaurants[spec["restaurant"]],
                rider=riders[spec["rider"]] if spec["rider"] else None,
                status=spec["status"],
                delivery_status=spec["delivery"],
                payment_status=spec["pay_status"],
                delivery_address=spec["address"],
                total=0,
            )
            order.save()  # generates ORDxxxxx

            total = 0
            for item_name, qty in spec["items"]:
                mi = menu[(spec["restaurant"], item_name)]
                OrderItem(order=order, menu_item=mi, quantity=qty, unit_price=mi.price).save()
                total += qty * mi.price
            order.total = total
            order.save()

            if spec["payment"]:
                method, pay_status = spec["payment"]
                prefix = "CASH" if method == "cash" else "TXN"
                Payment(
                    order=order, amount=total, method=method, status=pay_status,
                    transaction_id=f"{prefix}-{order.order_id}",
                    paid_at=timezone.now() if pay_status == "completed" else None,
                ).save()
                n_payments += 1

            if spec["review"]:
                rider_rating, rest_rating, comment = spec["review"]
                Review(
                    order=order, customer=order.customer,
                    rider_rating=rider_rating, restaurant_rating=rest_rating,
                    comment=comment,
                ).save()
                n_reviews += 1

        self.stdout.write(self.style.SUCCESS(
            f"Seeded {len(customers)} customers, {len(restaurants)} restaurants, "
            f"{len(riders)} riders, {len(menu)} menu items, {len(ORDERS)} orders, "
            f"{n_payments} payments, {n_reviews} reviews."
        ))